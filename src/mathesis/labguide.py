"""Lab guide: for a lab page, an LLM writes <lesson>-lab-guide.md with the gcloud commands (and Terraform for
what gcloud cannot create) that rebuild the lab's resources.

The backend is the `lab_guide` provider of the settings (llm.py): by default the `claude` CLI in headless mode
(`claude -p`: no tools, no session, an empty temporary folder, so it can only turn the lab text into text), or
Gemini / any OpenAI-compatible API / Ollama. When it is unavailable the lab is still saved, just without a guide.
"""
import re
import subprocess
from pathlib import Path

from . import gcloudcheck
from .config import Settings
from .llm import make_client, should_announce
from .notify import notify
from .obsidian import open_note, opener_name
from .pipeline import PROMPT_DIR


def guide_path(file: str | Path) -> Path:
    file = str(file)
    return Path(file[:-3] + "-lab-guide.md" if file.endswith(".md") else file + "-lab-guide.md")


def clean(text: str) -> str:
    """The guide, without a code fence the model may have wrapped around the whole document."""
    text = text.strip()
    fenced = re.fullmatch(r"```(?:markdown|md)?\s*\n(.*)\n```", text, re.S)
    return (fenced.group(1) if fenced else text).strip() + "\n"


def generate(content: str, file: str | Path, settings: Settings, run=subprocess.run, client=None) -> str:
    client = client or make_client(settings, "lab_guide", run)
    system = (PROMPT_DIR / "lab_guide.txt").read_text(encoding="utf-8")
    if getattr(client, "checks_commands", False):  # the model can read gcloud help: tell it to
        system += "\n\n" + (PROMPT_DIR / "lab_guide_check.txt").read_text(encoding="utf-8")
    title = re.sub(r"^\d+-", "", Path(file).stem)
    guide = clean(client.chat(system, f"Lab: {title}\n\nLab instructions:\n\n{content}"))
    if len(guide.split()) < 20:
        raise RuntimeError(f"{client.label} returned no usable guide: " + guide[:200])
    if settings.lab_check_commands and gcloudcheck.available():
        guide = repair(guide, system, client)
    return guide


CHECK_ROUNDS = 2


def repair(guide: str, system: str, client) -> str:
    """Check the guide's gcloud commands against the real help pages and have the model fix the wrong ones (any provider).

    A repaired guide replaces the old one only if it still has the guide's size and no more problems than before.
    """
    bad = gcloudcheck.problems(guide)
    for _ in range(CHECK_ROUNDS):
        if not bad:
            break
        message = ((PROMPT_DIR / "lab_guide_repair.txt").read_text(encoding="utf-8") + "\n\n## Guide\n\n" + guide
                   + "\n\n## Problems\n\n" + "\n".join(f"- `{c}` -> {why}" for c, why in bad)
                   + "\n\n## Help pages\n\n" + gcloudcheck.help_for(bad))
        try:
            fixed = clean(client.chat(system, message))
        except Exception as e:   # the first guide is still good
            print(f"Lab guide check: repair failed ({e}); keeping the guide as written")
            break
        now = gcloudcheck.problems(fixed)
        if len(fixed.split()) < len(guide.split()) * 0.6 or len(now) > len(bad):
            print("Lab guide check: the repaired guide is worse; keeping the previous one")
            break
        guide, bad = fixed, now
    return guide


def write_lab_guide(content: str, file: str | Path, settings: Settings, run=subprocess.run) -> str | None:
    """Generate and save <file>-lab-guide.md; report the outcome with a desktop notification."""
    name = Path(file).stem
    try:
        client = make_client(settings, "lab_guide", run)
        if client is None:
            return
        ok, problem = client.check()
        if not ok:  # fallback: the lab is already saved; just no guide
            print(f"No lab guide for {file}: {problem}. The lab text is saved.")
            if should_announce("lab_guide", problem):
                notify("Saved without lab guide", f"{name}: {problem}", enabled=settings.notify)
            return problem
        should_announce("lab_guide", None)
        print(f"Requesting lab guide ({client.label}) for {file}")
        guide = generate(content, file, settings, run, client)
        out = guide_path(file)
        out.write_text(guide + f"\n<!-- generated by {client.label} from the lab text; "
                       "check commands marked VERIFY before running them -->\n", encoding="utf-8")
        print(f"Lab guide written to {out}")
        on_click = (lambda: open_note(out, settings)) if settings.obsidian_open else None
        notify("Lab guide ready", name, enabled=settings.notify, on_click=on_click,
               action_label=f"Open in {opener_name(settings)}")
    except Exception as e:
        print(f"Error generating lab guide for {file}: {e}")
        notify("Lab guide failed", f"{name}: {e}", error=True, enabled=settings.notify)
        return str(e)