"""Lab guide: for a lab page, Claude Code writes <lesson>-lab-guide.md with the gcloud commands (and Terraform for
what gcloud cannot create) that rebuild the lab's resources.

This is done by the `claude` CLI in headless mode (`claude -p`), not by the Ollama pipeline: it has no tools, no
session and runs in an empty temporary folder, so it can only turn the lab text into text.
"""
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

from .config import Settings
from .notify import notify
from .obsidian import open_in_obsidian
from .pipeline import PROMPT_DIR


def guide_path(file: str | Path) -> Path:
    file = str(file)
    return Path(file[:-3] + "-lab-guide.md" if file.endswith(".md") else file + "-lab-guide.md")


def build_command(executable: str, system_prompt: str, model: str | None) -> list[str]:
    command = [executable, "-p", "--output-format", "text", "--tools", "", "--no-session-persistence",
               "--system-prompt", system_prompt]
    return command + (["--model", model] if model else [])


def clean(text: str) -> str:
    """The guide, without a code fence the model may have wrapped around the whole document."""
    text = text.strip()
    fenced = re.fullmatch(r"```(?:markdown|md)?\s*\n(.*)\n```", text, re.S)
    return (fenced.group(1) if fenced else text).strip() + "\n"


def generate(content: str, file: str | Path, settings: Settings, run=subprocess.run) -> str:
    executable = shutil.which(settings.claude_command)
    if not executable:
        raise RuntimeError(f"the Claude Code CLI '{settings.claude_command}' was not found (set MATHESIS_CLAUDE)")
    system = (PROMPT_DIR / "lab_guide.txt").read_text(encoding="utf-8")
    title = re.sub(r"^\d+-", "", Path(file).stem)
    message = f"Lab: {title}\n\nLab instructions:\n\n{content}"
    with tempfile.TemporaryDirectory(prefix="mathesis-claude-") as scratch:  # nothing of the project or the notes in reach
        done = run(build_command(executable, system, settings.claude_model), input=message, capture_output=True,
                   text=True, cwd=scratch, timeout=settings.claude_timeout)
    if done.returncode != 0:
        raise RuntimeError(f"claude exited with {done.returncode}: {(done.stderr or done.stdout).strip()[-300:]}")
    guide = clean(done.stdout)
    if len(guide.split()) < 20:
        raise RuntimeError("claude returned no usable guide: " + guide[:200])
    return guide


def write_lab_guide(content: str, file: str | Path, settings: Settings, run=subprocess.run) -> None:
    """Generate and save <file>-lab-guide.md; report the outcome with a desktop notification."""
    print(f"Requesting lab guide (Claude Code{', ' + settings.claude_model if settings.claude_model else ''}) for {file}")
    name = Path(file).stem
    try:
        guide = generate(content, file, settings, run)
        out = guide_path(file)
        out.write_text(guide + f"\n<!-- generated by Claude Code{' (' + settings.claude_model + ')' if settings.claude_model else ''}"
                       " from the lab text; check commands marked VERIFY before running them -->\n", encoding="utf-8")
        print(f"Lab guide written to {out}")
        on_click = (lambda: open_in_obsidian(out, settings.obsidian_command)) if settings.obsidian_open else None
        notify("Lab guide ready", name, enabled=settings.notify, on_click=on_click)
    except Exception as e:
        print(f"Error generating lab guide for {file}: {e}")
        notify("Lab guide failed", f"{name}: {e}", error=True, enabled=settings.notify)
